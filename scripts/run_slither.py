"""M2 baseline: run Slither on every dataset contract and record its findings.

Writes:
  results/slither/contracts/cNN.json  normalized findings + timing per contract
  results/slither/summary.json        machine info, totals, per-class counts
  results/slither/SUMMARY.md          the same as readable tables
  results/raw/slither/cNN.json        Slither's full JSON (git-ignored)

Usage:
  python scripts/run_slither.py                   # all contracts
  python scripts/run_slither.py --only c01 c02    # a subset (e.g. CI smoke test)
  python scripts/run_slither.py --out /tmp/x      # write somewhere else
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import statistics
import sys
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path

from auditor.dataset import DATASET_DIR, REPO_ROOT, load_labels, load_taxonomy
from auditor.slither_map import NO_DETECTOR_FOR
from auditor.slither_runner import run_one


def machine_info() -> dict:
    cpu = "unknown"
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                cpu = line.split(":", 1)[1].strip()
                break
    except OSError:
        pass
    ram_gb = None
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemTotal"):
                ram_gb = round(int(line.split()[1]) / 1024 / 1024, 1)
                break
    except OSError:
        pass
    kernel = platform.release()
    return {
        "cpu": cpu,
        "logical_cpus": os.cpu_count(),
        "ram_gb_visible": ram_gb,
        "os": f"{platform.system()} {kernel}" + (" (WSL)" if "microsoft" in kernel.lower() else ""),
        "python": platform.python_version(),
        "slither": version("slither-analyzer"),
        "crytic_compile": version("crytic-compile"),
        "run_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def aggregate(entries: list[dict], results: dict[str, dict]) -> dict:
    classes = list(load_taxonomy()["classes"])
    ok = [results[e["id"]] for e in entries if results[e["id"]]["success"]]
    times = [r["seconds"] for r in results.values()]
    all_f = [f for r in ok for f in r["findings"]]
    by_impact: dict[str, int] = {}
    for f in all_f:
        by_impact[f["impact"]] = by_impact.get(f["impact"], 0) + 1

    def predicted(cid: str) -> set[str]:
        return {f["class"] for f in results[cid]["findings"] if f["class"]}

    vuln = [e for e in entries if e["label"] == "vulnerable"]
    clean = [e for e in entries if e["label"] == "clean"]
    per_class = {}
    for c in classes:
        has = [e for e in entries if c in e["classes"]]
        hasnt = [e for e in entries if c not in e["classes"]]
        per_class[c] = {
            "contracts_with_class": len(has),
            "flagged_with_this_class": sum(c in predicted(e["id"]) for e in has),
            "flagged_without_having_it": sum(c in predicted(e["id"]) for e in hasnt),
        }
    return {
        "contracts_total": len(entries),
        "contracts_analyzed_ok": len(ok),
        "seconds_total": round(sum(times), 1),
        "seconds_mean": round(statistics.mean(times), 2) if times else None,
        "seconds_median": round(statistics.median(times), 2) if times else None,
        "seconds_max": round(max(times), 2) if times else None,
        "detector_results_total": len(all_f),
        "detector_results_mapped": sum(f["class"] is not None for f in all_f),
        "detector_results_unmapped": sum(f["class"] is None for f in all_f),
        "detector_results_by_impact": dict(sorted(by_impact.items())),
        "vulnerable_contracts": len(vuln),
        "vulnerable_flagged_any_mapped_class": sum(bool(predicted(e["id"])) for e in vuln),
        "clean_contracts": len(clean),
        "clean_flagged_any_mapped_class": sum(bool(predicted(e["id"])) for e in clean),
        "per_class": per_class,
        "classes_without_any_slither_detector": NO_DETECTOR_FOR,
    }


def write_markdown(out: Path, info: dict, agg: dict, entries: list[dict], results: dict) -> None:
    L = ["# Slither baseline (M2)", "",
         "Generated by `scripts/run_slither.py`. Numbers are from the machine below.", "",
         "| machine | |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in info.items()]
    L += ["", "## Totals", "", "| metric | value |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in agg.items() if not isinstance(v, (dict, list))]
    L += ["", "Detector results by Slither impact: "
          + ", ".join(f"{k} {v}" for k, v in agg["detector_results_by_impact"].items()), "",
          "## Per class (contract level)", "",
          "A contract counts as flagged for a class if any mapped Slither detector fires for it.", "",
          "| class | contracts with class | flagged, has class | flagged, does not have class |",
          "|---|---|---|---|"]
    for c, v in agg["per_class"].items():
        note = " (no Slither detector)" if c in agg["classes_without_any_slither_detector"] else ""
        L.append(f"| {c}{note} | {v['contracts_with_class']} | {v['flagged_with_this_class']} | "
                 f"{v['flagged_without_having_it']} |")
    L += ["", "## Per contract", "",
          "| id | label | true classes | Slither classes | mapped detectors | unmapped results | seconds |",
          "|---|---|---|---|---|---|---|"]
    for e in entries:
        r = results[e["id"]]
        mapped = sorted({f["check"] for f in r["findings"] if f["class"]})
        pred = sorted({f["class"] for f in r["findings"] if f["class"]})
        status = "" if r["success"] else " (FAILED)"
        L.append(f"| {e['id']} | {e['label']}{status} | {', '.join(e['classes']) or '-'} | "
                 f"{', '.join(pred) or '-'} | {', '.join(mapped) or '-'} | "
                 f"{sum(f['class'] is None for f in r['findings'])} | {r['seconds']} |")
    (out / "SUMMARY.md").write_text("\n".join(L) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="contract ids to run (default: all)")
    ap.add_argument("--out", default=str(REPO_ROOT / "results" / "slither"))
    args = ap.parse_args()

    entries = load_labels()
    if args.only:
        entries = [e for e in entries if e["id"] in set(args.only)]
        if not entries:
            sys.exit("no matching contract ids")
    out = Path(args.out)
    (out / "contracts").mkdir(parents=True, exist_ok=True)
    raw_dir = REPO_ROOT / "results" / "raw" / "slither"

    results = {}
    for i, e in enumerate(entries, start=1):
        r = run_one(DATASET_DIR / e["file"], e["solc_version"], raw_dir / f"{e['id']}.json")
        r = {"id": e["id"], "solc_version": e["solc_version"], **r}
        results[e["id"]] = r
        (out / "contracts" / f"{e['id']}.json").write_text(json.dumps(r, indent=2) + "\n")
        mapped = sum(f["class"] is not None for f in r["findings"])
        state = "ok" if r["success"] else "FAILED: " + str(r["error"])[:120]
        print(f"[{i:2d}/{len(entries)}] {e['id']} {state} {r['seconds']:.1f}s "
              f"results={len(r['findings'])} mapped={mapped}", flush=True)

    info = machine_info()
    agg = aggregate(entries, results)
    (out / "summary.json").write_text(json.dumps({"machine": info, **agg}, indent=2) + "\n")
    write_markdown(out, info, agg, entries, results)

    print(f"\nanalyzed ok: {agg['contracts_analyzed_ok']}/{agg['contracts_total']}")
    print(f"time: total {agg['seconds_total']}s, median {agg['seconds_median']}s per contract")
    print(f"vulnerable flagged (any mapped class): "
          f"{agg['vulnerable_flagged_any_mapped_class']}/{agg['vulnerable_contracts']}")
    print(f"clean flagged (any mapped class): {agg['clean_flagged_any_mapped_class']}/{agg['clean_contracts']}")
    print(f"detector results: {agg['detector_results_total']} total, "
          f"{agg['detector_results_mapped']} mapped, {agg['detector_results_unmapped']} unmapped")
    print(f"wrote {out}")
    if agg["contracts_analyzed_ok"] != agg["contracts_total"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
