"""M5: one command that turns every committed result into the evaluation report.

Reads dataset/labels.json, results/slither/ and results/llm/<run>/ (no API calls,
deterministic) and writes:
  results/eval/RESULTS.md     tables: headline, per class, variance, false positives, misses, cost
  results/eval/results.json   the same numbers, machine-readable

Usage:
  python scripts/evaluate.py           # write the report
  python scripts/evaluate.py --check   # fail if the committed report is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

from auditor.dataset import REPO_ROOT, load_labels
from auditor.metrics import classes, evaluate_tool, run_dirs, summary_of

OUT = REPO_ROOT / "results" / "eval"
BASE = [("slither", "Slither 0.11.6"), ("llm_only", "LLM only"), ("llm_slither", "LLM + Slither"),
        ("llm_rag", "LLM + RAG"), ("llm_both", "LLM + RAG + Slither")]


def fmt(x) -> str:
    return "n/a" if x is None else f"{x:.2f}"


def cost_row(name: str) -> tuple[str, str, str]:
    s = summary_of(name)
    if name == "slither":
        return "0 (local)", f"{s.get('seconds_median', 'n/a')} s local", "$0"
    per = s.get("tokens_per_contract_mean")
    return (f"{per}", f"{s.get('api_seconds_median', 'n/a')} s API",
            f"${s.get('cost_usd_at_paid_prices', 0):.4f} paid-tier / $0 free")


def variance(groups: dict[str, list[str]], results: dict) -> list[dict]:
    out = []
    for base, runs in groups.items():
        rs = [results[r] for r in runs if results.get(r)]
        if len(rs) < 2:
            continue
        ids = [e["id"] for e in load_labels()]
        sets = [{cid: frozenset(f["class"] for f in r["predictions"][cid]) for cid in ids} for r in rs]
        stable = sum(len({s[cid] for s in sets}) == 1 for cid in ids)
        f1 = [r["contract_level"]["micro"]["f1"] for r in rs]
        rec = [r["detection"]["recall"] for r in rs]
        clean = [r["detection"]["fp"] for r in rs]
        out.append({"base": base, "runs": runs, "contract_micro_f1": f1, "vulnerable_recall": rec,
                    "clean_flagged": clean, "contracts_with_identical_classes": f"{stable}/{len(ids)}"})
    return out


def build(out: Path) -> dict:
    entries = load_labels()
    by_id = {e["id"]: e for e in entries}
    all_runs = ["slither"] + run_dirs()
    results = {n: evaluate_tool(n) for n in all_runs}
    base = [(n, label) for n, label in BASE if results.get(n)]

    L = ["# Evaluation results (M5)", "",
         "Generated by `scripts/evaluate.py` from the committed result files; no API calls. "
         "49 contracts (31 vulnerable, 18 clean), model `openai/gpt-oss-120b` on Groq, Slither 0.11.6. "
         "Run on an Intel i5-10210U laptop (WSL Ubuntu); LLM time is Groq API round-trip.", "",
         "Definitions: **contract level** = right class anywhere in the contract; **function level** = right "
         "class in the right function; **detection** = is the contract vulnerable at all. "
         "The 95% interval resamples contracts (1,000 bootstrap draws, seed 0).", "",
         "## Headline", "",
         "| condition | contract P | contract R | contract F1 (95% CI) | macro F1 | function F1 | "
         "detection P / R | clean flagged |", "|---|---|---|---|---|---|---|---|"]
    for n, label in base:
        r = results[n]
        c, f, d = r["contract_level"], r["function_level"], r["detection"]
        lo, hi = r["contract_micro_f1_95ci"]
        L.append(f"| {label} | {fmt(c['micro']['precision'])} | {fmt(c['micro']['recall'])} | "
                 f"{fmt(c['micro']['f1'])} ({lo:.2f}-{hi:.2f}) | {fmt(c['macro']['f1'])} | "
                 f"{fmt(f['micro']['f1'])} | {fmt(d['precision'])} / {fmt(d['recall'])} | {d['fp']}/18 |")

    L += ["", "## Per class, contract level: F1 (precision / recall)", "",
          "| class | n | " + " | ".join(label for _, label in base) + " |",
          "|---|---|" + "---|" * len(base)]
    for c in classes():
        n = sum(c in e["classes"] for e in entries)
        cells = []
        for name, _ in base:
            v = results[name]["contract_level"]["per_class"][c]
            cells.append(f"{fmt(v['f1'])} ({fmt(v['precision'])} / {fmt(v['recall'])})")
        L.append(f"| {c} | {n} | " + " | ".join(cells) + " |")

    groups: dict[str, list[str]] = {}
    for n in run_dirs():
        groups.setdefault(re.sub(r"_r\d+$", "", n), []).append(n)
    var = variance(groups, results)
    L += ["", "## Run-to-run variance", ""]
    if var:
        L += ["Repeat runs send the identical request again (temperature 0) with the cache bypassed.", "",
              "| condition | runs | contract micro F1 per run | vulnerable recall per run | "
              "clean flagged per run | contracts with identical predicted classes |", "|---|---|---|---|---|---|"]
        for v in var:
            L.append(f"| {v['base']} | {len(v['runs'])} | {', '.join(fmt(x) for x in v['contract_micro_f1'])} | "
                     f"{', '.join(fmt(x) for x in v['vulnerable_recall'])} | "
                     f"{', '.join(str(x) for x in v['clean_flagged'])} | {v['contracts_with_identical_classes']} |")
    else:
        L.append("Not measured yet (no repeat runs committed).")

    slither_units = {(cid, f["class"]) for cid, fs in results["slither"]["predictions"].items() for f in fs}
    L += ["", "## False positives on clean contracts", "",
          "Every finding a tool reported on a contract labeled clean. `Slither too` = Slither "
          "reported the same class on the same contract (for runs given Slither output, a possible echo).", "",
          "| condition | contract | role | class | function | Slither too | reasoning or detector |",
          "|---|---|---|---|---|---|---|"]
    fp_summary = {}
    for n, label in base:
        rows = []
        for cid, fs in results[n]["predictions"].items():
            if by_id[cid]["label"] != "clean":
                continue
            for f in fs:
                why = f.get("reasoning") or f.get("check") or ""
                why = why.replace("|", "/").replace("\n", " ")[:160]
                echo = "yes" if n != "slither" and (cid, f["class"]) in slither_units else ""
                rows.append((cid, by_id[cid]["role"], f["class"], ", ".join(f["fns"]), echo, why))
        rows = sorted(set(rows))
        fp_summary[n] = {"findings": len(rows), "contracts": len({r[0] for r in rows}),
                         "on_hard_negatives": sum(r[1] == "negative_sample" for r in rows),
                         "echo_slither": sum(r[4] == "yes" for r in rows)}
        L += [f"| {label} | {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |" for r in rows]
    L += ["", "| condition | false-positive findings | clean contracts affected | on hard negatives | Slither flagged the same |",
          "|---|---|---|---|---|"]
    L += [f"| {label} | {fp_summary[n]['findings']} | {fp_summary[n]['contracts']} | "
          f"{fp_summary[n]['on_hard_negatives']} | {fp_summary[n]['echo_slither']} |" for n, label in base]

    gold = {(e["id"], f["class"]) for e in entries for f in e["findings"]}
    found = {(cid, f["class"]) for n, _ in base for cid, fs in results[n]["predictions"].items() for f in fs}
    missed = sorted(gold - found)
    L += ["", "## Missed by every condition", "",
          f"{len(missed)} of {len(gold)} labeled (contract, class) pairs were not reported by any tool or condition.", "",
          "| contract | class | labeled function | note |", "|---|---|---|---|"]
    for cid, c in missed:
        fn = ", ".join(sorted({f["function"] for f in by_id[cid]["findings"] if f["class"] == c}))
        L.append(f"| {cid} | {c} | {fn} | {by_id[cid]['notes'][:140]} |")

    L += ["", "## Cost and time per contract", "",
          "| condition | tokens per contract | median time per contract | total cost (49 contracts) |",
          "|---|---|---|---|"]
    for n, label in base:
        t, s, usd = cost_row(n)
        L.append(f"| {label} | {t} | {s} | {usd} |")

    out.mkdir(parents=True, exist_ok=True)
    (out / "RESULTS.md").write_text("\n".join(L) + "\n")
    data = {n: {k: v for k, v in r.items() if k != "predictions"} for n, r in results.items() if r}
    data["_variance"] = var
    data["_false_positives"] = fp_summary
    data["_missed_by_all"] = [list(m) for m in missed]
    (out / "results.json").write_text(json.dumps(data, indent=2) + "\n")
    return data


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            build(Path(tmp))
            same = all((Path(tmp) / f).read_text() == (OUT / f).read_text()
                       for f in ("RESULTS.md", "results.json") if (OUT / f).exists()) and (OUT / "RESULTS.md").exists()
        if not same:
            print("results/eval/ is out of date; run scripts/evaluate.py and commit it")
            sys.exit(1)
        print("check passed: committed evaluation report matches the committed results")
        return
    data = build(OUT)
    for n, label in BASE:
        if n in data:
            c = data[n]["contract_level"]["micro"]
            print(f"{label:22} contract P {fmt(c['precision'])} R {fmt(c['recall'])} F1 {fmt(c['f1'])}  "
                  f"function F1 {fmt(data[n]['function_level']['micro']['f1'])}")
    print(f"variance groups measured: {len(data['_variance'])}")
    print(f"missed by every condition: {len(data['_missed_by_all'])}")
    print(f"wrote {OUT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
